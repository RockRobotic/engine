import { readFile } from 'node:fs/promises';

import { expect } from 'chai';
import { restore, stub } from 'sinon';

import { Asset } from '../../../src/framework/asset/asset.js';
import { GSplatAssetLoader } from '../../../src/framework/components/gsplat/gsplat-asset-loader.js';
import { PlyParser, isAntiAliased } from '../../../src/framework/parsers/ply.js';
import { http } from '../../../src/platform/net/http.js';
import { createApp } from '../../app.mjs';
import { jsdomSetup, jsdomTeardown } from '../../jsdom.mjs';

describe('PlyParser', function () {

    afterEach(function () {
        restore();
        http.withCredentials = false;
    });

    // the parser streams the ply with fetch rather than through the http layer, so it has to apply
    // the credentials flag itself. The request is failed as soon as its arguments are recorded.
    const loadCredentials = async () => {
        const fetched = stub(global, 'fetch').rejects(new Error('recorded'));
        const parser = Object.create(PlyParser.prototype);
        parser.app = { scene: {} };

        await new Promise((resolve) => {
            parser.load({ load: 'test.ply', original: 'test.ply' }, resolve, new Asset('test', 'gsplat'));
        });

        return fetched.firstCall.args[1]?.credentials;
    };

    // ROCK fork: gsplat streams always send credentials, whatever http.withCredentials says, so
    // that CloudFront signed cookies authorize them.
    it('streams with credentials by default', async function () {
        expect(await loadCredentials()).to.equal('include');
    });

    it('streams with credentials once they are enabled', async function () {
        http.withCredentials = true;

        expect(await loadCredentials()).to.equal('include');
    });

    it('discards a withdrawn environment PLY and reloads it when visible again', async function () {
        const bytes = await readFile(new URL('../../assets/test.ply', import.meta.url));
        jsdomSetup();
        const app = createApp();
        const loader = new GSplatAssetLoader(app.assets);
        try {
            const url = '/environment.ply';
            const textures = app.graphicsDevice.textures.size;
            let finish;
            const firstResponse = new Promise((resolve) => {
                finish = resolve;
            });
            const fetch = stub(global, 'fetch');
            fetch.onFirstCall().returns(firstResponse);
            fetch.onSecondCall().resolves(new Response(bytes));

            loader.load(url);
            const original = app.assets.getByUrl(url);
            loader.unload(url);
            loader.load(url); // this request joins the old URL until its callback has settled
            const replacement = app.assets.getByUrl(url);
            const settled = new Promise((resolve, reject) => {
                replacement.once('load', resolve);
                replacement.once('error', reject);
            });
            finish(new Response(bytes));
            await settled;
            expect(original.resource).to.be.null;
            expect(app.loader.getFromCache(url, 'gsplat')).to.be.undefined;
            expect(app.graphicsDevice.textures.size).to.equal(textures);

            const ready = new Promise((resolve, reject) => {
                replacement.once('load', resolve);
                replacement.once('error', reject);
            });
            loader.load(url);
            await ready;
            expect(loader.getResource(url).numSplats).to.equal(64);
            expect(fetch.callCount).to.equal(2);
        } finally {
            loader.destroy();
            app.destroy();
            jsdomTeardown();
        }
    });
});

describe('isAntiAliased', function () {

    it('returns false without a training mode comment', function () {
        expect(isAntiAliased([])).to.equal(false);
        expect(isAntiAliased(['Generated by some tool', 'vertical axis: y'])).to.equal(false);
    });

    it('reads the Postshot comment', function () {
        // the header comments of a Postshot v1.1.69 export trained with anti-aliasing
        expect(isAntiAliased(['Postshot v1.1.69', 'postshot.anti_aliasing=1', 'postshot.color.primaries=sRGB', 'postshot.color.eotf=sRGB'])).to.equal(true);
        // without anti-aliasing Postshot omits the line
        expect(isAntiAliased(['Postshot v1.1.69', 'postshot.color.eotf=sRGB'])).to.equal(false);
        expect(isAntiAliased(['postshot.anti_aliasing=0'])).to.equal(false);
    });

    it('does not read `antialiased 1`, which no producer writes', function () {
        expect(isAntiAliased(['antialiased 1'])).to.equal(false);
    });

    it('reads the Brush and splat-transform comment', function () {
        expect(isAntiAliased(['SplatRenderMode: mip'])).to.equal(true);
        expect(isAntiAliased(['SplatRenderMode: default'])).to.equal(false);
        expect(isAntiAliased(['SplatRenderMode: 2dgs'])).to.equal(false);
    });

    it('matches case-insensitively', function () {
        expect(isAntiAliased(['POSTSHOT.ANTI_ALIASING=1'])).to.equal(true);
        expect(isAntiAliased(['  splatrendermode:   MIP  '])).to.equal(true);
    });

    it('lets the last matching comment win', function () {
        expect(isAntiAliased(['postshot.anti_aliasing=1', 'SplatRenderMode: default'])).to.equal(false);
        expect(isAntiAliased(['SplatRenderMode: default', 'postshot.anti_aliasing=1'])).to.equal(true);
    });

    it('ignores unrecognized values', function () {
        expect(isAntiAliased(['postshot.anti_aliasing=1', 'postshot.anti_aliasing=maybe'])).to.equal(true);
        expect(isAntiAliased(['SplatRenderMode: mip', 'SplatRenderMode: unknown'])).to.equal(true);
    });
});
